-- RK Mines Diesel Ledger
-- Run this once in the Supabase SQL Editor for the connected project.

create table if not exists public.vehicles (
  id bigint generated by default as identity primary key,
  vehicle_no text not null unique,
  vehicle_name text not null,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.staff_members (
  id bigint generated by default as identity primary key,
  name text not null,
  role text not null check (role in ('operator', 'issuer')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (name, role)
);

create table if not exists public.diesel_records (
  id bigint generated by default as identity primary key,
  date date not null,
  vehicle_id bigint not null references public.vehicles(id),
  opening_balance numeric(12, 2) not null default 0,
  reading numeric(12, 2),
  diesel_issued numeric(12, 2) not null default 0,
  diesel_purchased numeric(12, 2) not null default 0,
  closing_balance numeric(12, 2) not null default 0,
  operator text not null,
  issuer text not null,
  created_at timestamptz not null default now()
);

create index if not exists diesel_records_date_idx
  on public.diesel_records (date, created_at, id);

create index if not exists diesel_records_vehicle_idx
  on public.diesel_records (vehicle_id);

alter table public.vehicles enable row level security;
alter table public.staff_members enable row level security;
alter table public.diesel_records enable row level security;

drop policy if exists "authenticated users can manage vehicles" on public.vehicles;
create policy "authenticated users can manage vehicles"
  on public.vehicles for all to authenticated using (true) with check (true);

drop policy if exists "authenticated users can manage staff" on public.staff_members;
create policy "authenticated users can manage staff"
  on public.staff_members for all to authenticated using (true) with check (true);

drop policy if exists "authenticated users can manage diesel records" on public.diesel_records;
create policy "authenticated users can manage diesel records"
  on public.diesel_records for all to authenticated using (true) with check (true);

