-- Optional opening stock entry for the first working day.
insert into public.diesel_records (
  date, vehicle_id, opening_balance, reading, diesel_issued,
  diesel_purchased, closing_balance, operator, issuer
)
select
  current_date, id, 0, null, 0, 1200, 1200, 'System opening', 'Store desk'
from public.vehicles
where vehicle_no = 'EX-07'
  and not exists (
    select 1 from public.diesel_records where date = current_date
  );

